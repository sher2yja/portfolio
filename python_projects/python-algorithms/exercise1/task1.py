#Задание 1. Скалярное произведение двух векторов

#Объявдение функции read_vector - для ввода,
#которая читает одну строку и возвращает список чисел
def read_vector():
#   Читает одну строку и возвращает список чисел
    return [float(x) for x in input().split()]
#   input()          прочитал строку с клавиатуры
#   .split()         режет её на кусочки: по умолчанию режет
#                    по любому пробельному символу
#   for x in ...     цикл для перебора того что ввели
#   float(x)         превращает строку в число с плавающей точкой

#Функция с двумя параметрами. При вызове в v1 и v2 попадут два списка.
def dot_product(v1, v2):
    #Возвращает скалярное произведение двух векторов
    return sum(a * b for a, b in zip(v1, v2))
    # zip(v1, v2) выдаёт пары: сначала первые элементы обоих списков,
    #   потом вторые, потом третьи.
    # for a, b in ... раскладывает каждую пару по двум именам сразу.
    # a * b считается для каждой пары.
    # sum(...) складывает все результаты в одно число.


#Основная функция
def main():
    v1 = read_vector()          #   объявление переменных v1 и v2,
    v2 = read_vector()          #   в которые попадут два списка чисел из read_vector
    print(dot_product(v1, v2))  #   принтем значение которое вернет функция
#   dot_product


#Точка входа в программу
if __name__ == '__main__':
    main()
#   __name__         служебная переменная, Python сам кладёт в неё
#                    имя модуля - ещё до выполнения первой строки
#   '__main__'       такое значение бывает только у файла,
#                    запущенного напрямую: python3 task1.py
#                    при импорте туда попадёт 'task1', условие станет
#                    ложным и main() не запустится - импортировавший
#                    получит только функции, без чтения с клавиатуры
#   main()           скобки обязательны: имя без скобок не запускает
#                    функцию, а лишь вычисляет сам объект-функцию

