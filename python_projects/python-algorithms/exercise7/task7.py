#Задание 7. Робот
#Робот идёт из левого верхнего угла в правый нижний, шагая только вниз
#или вправо, и собирает монеты с каждой клетки, по которой прошёл.
#Надо узнать, сколько монет он соберёт на самом выгодном маршруте.

#Функция принимает поле (список списков) и возвращает число монет.
#Приём называется «динамика»: вместо перебора всех маршрутов заполняем
#вспомогательную таблицу dp, где в каждой клетке лежит лучший результат
#для пути ДО неё. Тогда ответ сам окажется в последней клетке.
def max_coins(field):
    n = len(field)                  # сколько строк
    m = len(field[0])               # сколько столбцов

    dp = [[0] * m for _ in range(n)]    # таблица того же размера из нулей

    for i in range(n):              # идём сверху вниз
        for j in range(m):          # и слева направо - так к моменту
                                    # расчёта клетки соседи сверху и
                                    # слева уже посчитаны
            from_top = 0
            from_left = 0

            if i > 0:               # в верхней строке сверху ничего нет
                from_top = dp[i - 1][j]
            if j > 0:               # в левом столбце слева ничего нет
                from_left = dp[i][j - 1]

            dp[i][j] = max(from_top, from_left) + field[i][j]
            #в клетку можно прийти только сверху или слева. Берём тот
            #вариант, где монет больше, и добавляем монеты самой клетки

    return dp[n - 1][m - 1]         # правый нижний угол и есть ответ


#Основная функция
def main():
    n, m = map(int, input().split())
    #map применяет int к каждому куску: '3 4' -> 3 и 4.
    #Слева два имени, справа два значения - это распаковка

    field = [list(map(int, input().split())) for _ in range(n)]
    #n раз читаем строку и превращаем её в список чисел. list() нужен
    #потому, что map отдаёт не список, а «ленивый» объект

    print(max_coins(field))


if __name__ == '__main__':
    main()
