#Задание 2. Палиндром
#Палиндром - число, которое читается одинаково слева направо
#и справа налево. Без строк. Отрицательные числа палиндромами не считаем.

#Функция принимает одно число и возвращает True или False.
#Идея: собрать из числа его зеркальную копию и сравнить с оригиналом.
def is_palindrome(number):
    if number < 0:      # number < 0 по условию отрицательные не палиндромы,
        return False    # выходим сразу - дальше считать незачем

    original = number   # оригинальное число изменится, сохраняем в original
    reversed_number = 0 # сюда собираем перевёрнутое число

    while number > 0:           # крутимся, пока в числе остались цифры
        digit = number % 10     # остаток от деления на 10 - последняя цифра
        #сдвигаем уже собранное на разряд влево и дописываем к нему digit
        reversed_number = reversed_number * 10 + digit
        number //= 10           # целочисленное деление отрезает последнюю цифру

    return original == reversed_number  #сравниваем исходное и перевёрнутое числа
    #если совпало, то палиндром


def main():
    number = int(input())
    print(is_palindrome(number)) #   печатает что вернула is_palindrome: True / False

if __name__ == '__main__':
    main()