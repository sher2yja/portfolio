#Задание 4. Треугольник Паскаля
#Каждое число внутри треугольника - сумма двух чисел над ним.
#По условию ввод надо проверять: если это не натуральное число,
#печатаем ровно «Natural number was expected» и выходим.

#Функция строит треугольник из n строк и возвращает его списком
#списков: [[1], [1, 1], [1, 2, 1], [1, 3, 3, 1], ...]
def build_pascal_triangle(n):
    triangle = []                   # сюда сложим готовые строки

    for i in range(n):              # i - номер строки, считаем с нуля
        row = [1] * (i + 1)         # строка нужной длины, вся из единиц
        #в строке i ровно i+1 чисел, а по краям всегда стоят единицы -
        #их и оставим, посчитать надо только середину

        if i >= 2:                  # у строк 0 и 1 середины нет
            previous = triangle[i - 1]  # предыдущая, уже посчитанная строка

            for j in range(1, i):   # j от 1 до i-1 - это и есть середина
                row[j] = previous[j - 1] + previous[j]
                #каждое число середины = сумма двух соседей сверху

        triangle.append(row)        # строка готова, кладём в треугольник

    return triangle


#Основная функция
def main():
    try:
        text = input().strip()
    except EOFError:
        print('Natural number was expected')
        return
    #Ввод может кончиться, не дав ни одной строки: пустой поток или файл.
    #Это тоже некорректные данные, а условие требует по ним сообщение,
    #а не трейсбек - поэтому EOFError ловится здесь же

    if text.startswith('+'):        # +5 это тоже натуральное число,
        text = text[1:]             # плюс отрезаем, дальше он мешал бы

    if not text.isdecimal() or int(text) == 0:
        print('Natural number was expected')
        return                      # return без значения = просто выйти
    #isdecimal() истинно, только если в строке одни обычные цифры 0-9:
    #'f' и '-3' отсеются. Похожий isdigit() сюда не годится - он считает
    #цифрой ещё и надстрочные знаки вроде ², а int() их не принимает,
    #и программа падала бы с трейсбеком вместо сообщения.
    #Ноль проверяем отдельно - натуральным он не считается.
    #Текст ошибки задан условием дословно, менять его нельзя

    n = int(text)

    for row in build_pascal_triangle(n):
        print(*row)                 # звёздочка распаковывает список в
                                    # отдельные аргументы: print(*[1,2,1])
                                    # это то же самое, что print(1, 2, 1)


if __name__ == '__main__':
    main()
