#Задание 8. Различные числа
#Считаем, сколько РАЗНЫХ чисел ввёл пользователь.
#Повторы не в счёт: в 5 3 7 3 6 3 5 2 9 4 всего 7 разных чисел.

def main():
    n = int(input())
    numbers = set()         # множество хранит только уникальные значения,
                            # повтор оно просто не добавит второй раз

    for _ in range(n):
        numbers.add(int(input()))   # add() кладёт число в множество
    #подчёркивание вместо имени значит «номер витка не нужен,
    #важно только повторить нужное число раз»

    print(len(numbers))     # len() множества = сколько в нём разных чисел


if __name__ == '__main__':
    main()