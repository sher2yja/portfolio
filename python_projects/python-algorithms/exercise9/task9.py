#Задание 9. Производная в точке
#Многочлен задан коэффициентами, начиная со старшей степени.
#Ввод 2 3.0 / 5 / 1.2 / -3 означает 5*x**2 + 1.2*x - 3 в точке x = 3.0.
#Производная считается по правилу: c * x**k превращается в c*k * x**(k-1).
#Свободный член при этом исчезает - производная числа равна нулю.
# 2 3.0     <- N = 2 и x = 3.0
# 5         <- коэффициент при x**2
# 1.2       <- коэффициент при x**1
# -3        <- коэффициент при x**0



def main():
    n, x = input().split()  # первая строка: старшая степень и точка
    n = int(n)              # n - степень, целое число
    x = float(x)            # x - точка, вещественное число

    coefficients = [float(input()) for _ in range(n + 1)]
    #коэффициентов на один больше, чем степень: у 5*x**2 + 1.2*x - 3
    #степень 2, а чисел три. Первым идёт коэффициент при старшей степени

    derivative = 0.0        # сюда накапливаем ответ
    degree = n              # степень текущего слагаемого, идём от старшей

    for coefficient in coefficients[:-1]:
        derivative += coefficient * degree * (x ** (degree - 1))
        degree -= 1         # следующее слагаемое на степень ниже
    #[:-1] это срез «всё, кроме последнего»: свободный член пропускаем,
    #в производную он ничего не даёт.
    #** это возведение в степень: x ** 2 читается как x в квадрате

    print(f'{derivative:.3f}')
    #f-строка: в фигурных скобках имя, после двоеточия формат вывода.
    #.3f = вещественное с тремя знаками после точки, как требует условие


if __name__ == '__main__':
    main()
