#Задание 3. Фигуры
#В квадратной матрице из нулей и единиц считаем «квадраты» и «круги».
#Единицы - тело фигуры, нули - пустота. Фигуры не соприкасаются.
#Данные берём из файла input.txt, поэтому запускать надо из этой папки:
#cd exercise3 && python3 task3.py     (или ../run.py 3 из корня)

#Функция читает файл и возвращает таблицу - список списков чисел.
#Параметров нет: имя файла задано условием и зашито внутрь.
def read_matrix():
    matrix = []                             # сюда сложим строки таблицы

    with open('input.txt', 'r') as f:       # with сам закроет файл на выходе
    # r - read
        for line in f:
            line = line.strip()             # срезаем пробелы в конце строки
            #Без неё пустая строка дала пустой список [], потом len(matrix[0])
            # или обращение к клетке упало бы, потому дальше:
            if line == '':
                continue                    # continue = к следующему витку
            # страховка, если пустая строка в середине или в конце
            matrix.append([int(x) for x in line.split()])
            #через split нарезаю числа через пробел для массива

    return matrix


#Функция собирает ОДНУ фигуру целиком, начиная с клетки (start_row, start_col).
#Приём называется «заливка» (flood fill): встали на клетку фигуры
#и расползаемся от неё по соседям, пока есть куда идти.
#Подобным образом делали на бассейне игру в жизнь.
#visited общий на всю программу - в нём отмечаем пройденные клетки,
#чтобы не ходить по кругу и не посчитать одну фигуру дважды.
def collect_figure(matrix, visited, start_row, start_col):
    rows = len(matrix)                  # сколько строк в таблице
    cols = len(matrix[0])               # длина 1(0) строки = сколько столбцов

    to_visit = [(start_row, start_col)] # очередь дел: куда ещё не сходили
    #круглые скобки - это кортеж, пара чисел одним значением: координата клетки
    visited[start_row][start_col] = True    # метим сразу, иначе соседи
                                            # вернут нас в эту же клетку

    cells = []                          # сюда соберём клетки фигуры

    while to_visit:                     # пустой список = ложь, значит цикл
                                        # идёт, пока в очереди что-то есть
        row, col = to_visit.pop()      # берём два элемента из списка
        #и присваиваем их переменным row и col
        #pop забирает последний элемент и удаляет его из списка.
        #Дело сделано — клетка уходит из очереди и попадает в состав фигуры.
        cells.append((row, col))        # записали клетку в состав фигуры

        neighbours = [                  # четыре соседа, по диагонали не ходим
            (row + 1, col),             # вниз
            (row - 1, col),             # вверх
            (row, col + 1),             # вправо
            (row, col - 1),             # влево
        ]

        for r, c in neighbours:
            if r < 0 or r >= rows or c < 0 or c >= cols:
                continue                # сосед вылез за край таблицы
            if visited[r][c]:
                continue                # уже были тут, второй раз не идём
            if matrix[r][c] == 0:
                continue                # ноль - пустота, не часть фигуры

            visited[r][c] = True        # метим и кладём в очередь: дойдём
            to_visit.append((r, c))     # до него на следующем витке while

    return cells                        # очередь пуста - фигура обойдена


#Функция решает, квадрат перед нами или круг.
#Приём: обводим фигуру прямоугольной рамкой по крайним клеткам.
#У квадрата рамка забита единицами полностью, у круга - нет, углы срезаны.
def is_square(cells):
    rows = [row for row, col in cells]  # из каждой пары берём номер строки
    cols = [col for row, col in cells]  # и отдельно номер столбца

    height = max(rows) - min(rows) + 1  # высота рамки. +1 потому что считаем
    width = max(cols) - min(cols) + 1   # клетки: со 2-й по 4-ю строку их 3

    return height * width == len(cells)
    #height * width - сколько клеток влезло бы в рамку целиком.
    #Столько же, сколько в фигуре - рамка заполнена, это квадрат.
    #Меньше - внутри рамки дырки, это круг.


def main():
    matrix = read_matrix()          # таблица из файла
    rows = len(matrix)              # количество строк
    cols = len(matrix[0])           # количество колонок = длина 1(0) строки

    visited = [[False] * cols for _ in range(rows)]
    #таблица того же размера, вся из False. [False] * cols делает строку нужной
    #длины, а for _ in range(rows) повторяет её rows раз. Подчёркивание вместо
    #имени значит «значение не нужно, важно только повторить нужное число раз»

    squares = 0
    circles = 0
    # счётчики для фигур

    for row in range(rows):
        for col in range(cols):     # обычный двойной цикл для прогона по массиву
            if matrix[row][col] == 0 or visited[row][col]:
                continue            # пусто или уже посчитано - идём дальше
            #так в каждую фигуру заходим ровно один раз, через первую
            #встреченную клетку: остальные её клетки уже окажутся в visited

            cells = collect_figure(matrix, visited, row, col)

            if len(cells) <= 1:
                continue            # длина 1 или меньше = не фигура

            if is_square(cells):
                squares += 1        # квадрат +1, если квадрат, иначе круг
            else:
                circles += 1

    print(squares, circles)

if __name__ == '__main__':
    main()
