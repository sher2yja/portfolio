#!/bin/bash
#
# Доставка собранного бинарника на целевой сервер.
# Вызывается стадией deploy, которая запускается вручную.
#
# Бинарник берётся из каталога артефактов, выгруженного стадией сборки, —
# то есть доставляется ровно тот файл, который прошёл тесты, а не собранный
# заново на этой стадии.
#
# Пароль не запрашивается: открытый ключ пользователя, под которым работает
# раннер, заранее добавлен в authorized_keys пользователя devops на целевой
# машине. Настройка выполняется один раз вне репозитория.
#
# Адрес 192.168.100.12 — виртуальная машина учебного стенда. Реального
# сервера за ним нет, подставлять сюда рабочий адрес не следует.
#
# В сданной работе путь был src/artifacts/DO: скрипт лежал в src/ рядом
# с каталогом артефактов. В портфолио уровень src/ убран, путь приведён
# к новой раскладке.

scp artifacts/DO devops@192.168.100.12:/usr/local/bin
