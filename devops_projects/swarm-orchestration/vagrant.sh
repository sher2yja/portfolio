#!/bin/bash
# Выгрузка модулей KVM.
#
# VirtualBox и KVM не могут одновременно занимать аппаратную виртуализацию:
# если модули KVM загружены, VirtualBox откажется стартовать виртуальную
# машину. На хостах, где KVM подтягивается автоматически, эти две команды
# показывают, что загружено, и освобождают процессор для VirtualBox.
#
# Изменение действует до перезагрузки.

lsmod | grep kvm
sudo modprobe -r kvm_intel kvm