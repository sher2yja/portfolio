#!/bin/bash

# Проверка «строка состоит только из цифр» для main.sh.
#
# Скрипт ничего не печатает — результат передаётся кодом возврата, чтобы
# вызывающая сторона могла подставить его прямо в условие if.
#
# Соглашение здесь обратное привычному: 0 (успех) означает «это число».

is_number() {
  local re='^[0-9]+$'
  if [[ $1 =~ $re ]]; then
    return 0
  else
    return 1
  fi
}

if is_number "$1"; then
  exit 0
else
  exit 1
fi
