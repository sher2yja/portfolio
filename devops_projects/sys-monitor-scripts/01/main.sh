#!/bin/bash

# Часть 1. Проверка входного параметра.
#
# Задача части — научиться разбирать аргументы и отсекать некорректный ввод
# до того, как скрипт начнёт что-то делать.
#
# Проверка «параметр не число» вынесена в отдельный файл util.sh и работает
# через КОД ВОЗВРАТА, а не через вывод: util.sh завершается с 0, если это
# число, и с 1 иначе. Поэтому здесь достаточно поставить вызов прямо в if.

if [ $# -ne 1 ]; then
  echo "Необходимо ввести один текстовый параметр"
  exit 1
fi

param="$1"

if [ -z "$param" ]; then
    echo "Параметр не может быть пустым"
    exit 1
fi

# util.sh ищется рядом с этим скриптом, а не в текущем каталоге:
# иначе запуск вида bash 01/main.sh из родительской папки не находил бы его
if "$(dirname "$0")/util.sh" "$param"; then
  echo "Параметр не может быть числом"
  exit 1
else
  echo "Параметр: $param"
fi
