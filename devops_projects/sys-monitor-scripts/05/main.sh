#!/bin/bash

# Часть 5. Сбор статистики по каталогу.
#
# Точка входа: разбирает аргумент, проверяет его и раздаёт работу двум
# скриптам — count.sh считает количества, top.sh строит рейтинги.
#
# Требование завершающего «/» в пути взято из условия задачи: так параметр
# однозначно читается как каталог, а не как файл.
#
# Вложенные скрипты вызываются через $(dirname "$0"), а не по относительному
# пути: иначе запуск из другого каталога сломал бы их поиск.
#
# Время работы замеряется с точностью до наносекунд через date +%s.%N,
# разница считается bc — bash не умеет вычитать дробные числа.

# Проверка наличия параметра
if [ $# -ne 1 ]; then
    echo "Ошибка: отсутствует параметр пути. Или введено более одного параметра"
    exit 1
fi

# Проверка что параметр заканчивается на /
if [[ ! "$1" =~ /$ ]]; then
    echo "Ошибка: путь должен заканчиваться на символ «/»."
    exit 1
fi

# Проверка что директория существует
if [ ! -d "$1" ]; then
    echo "Ошибка: каталог «$1» не существует."
    exit 1
fi

# Засекаем время начала выполнения
start_time=$(date +%s.%N)

# Получаем абсолютный путь
DIR_PATH=$(realpath "$1")

bash "$(dirname "$0")/count.sh" "$DIR_PATH"
bash "$(dirname "$0")/top.sh" "$DIR_PATH"

# Время выполнения скрипта
end_time=$(date +%s.%N)
elapsed_time=$(echo "$end_time - $start_time" | bc)
echo "Script execution time (in seconds) = $elapsed_time"