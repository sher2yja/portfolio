/*
 * Часть 3. Мини веб-сервер на FastCGI.
 *
 * nginx не умеет выполнять программы сам: он умеет передавать запрос
 * постороннему процессу по протоколу FastCGI и вернуть клиенту его ответ.
 * Эта программа и есть такой процесс.
 *
 * Обычная программа CGI запускается заново на каждый запрос. FastCGI
 * работает иначе: процесс поднимается один раз и в цикле принимает запросы,
 * поэтому не платит за запуск при каждом обращении. Отсюда и цикл ниже:
 * FCGI_Accept() блокируется до прихода следующего запроса и возвращает
 * отрицательное значение, только когда соединение закрыто окончательно.
 *
 * Заголовок Content-Type отделяется от тела пустой строкой — это требование
 * протокола, без него nginx не поймёт, где заканчиваются заголовки.
 *
 * Сборка: gcc -o server server.c -lfcgi
 * Запуск: spawn-fcgi -p 8080 -n ./server
 */

#include <fcgi_stdio.h>
#include <stdlib.h>

int main(void) {
    while (FCGI_Accept() >= 0) {
        printf("Content-Type: text/html\r\n\r\n"
        "<html><body>\n"
        "<h1>Hello World!</h1>\n"
        "</body></html>\n");
    }
    return 0;
}