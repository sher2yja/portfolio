#!/bin/bash

# Часть 5. Разбор логов nginx через awk.
#
# Четыре режима, номер — единственный параметр: все записи по коду ответа,
# уникальные IP, только ошибки 4xx/5xx, уникальные IP среди ошибочных.
#
# В формате COMBINED девятое поле — код ответа, первое — адрес клиента.
# Отсюда $9 и $1 в выражениях awk.
#
# Логи берутся из соседней папки 04 — их предварительно создаёт часть 4.
# parse_logs.sh — разбор логов nginx через awk (задание 5)

# Проверка наличия параметра
if [ $# -ne 1 ]; then
  echo "Ошибка: требуется ровно 1 параметр (1, 2, 3 или 4)" >&2
  exit 1
fi

MODE="$1"
if ! [[ "$MODE" =~ ^[1-4]$ ]]; then
  echo "Ошибка: параметр должен быть числом 1, 2, 3 или 4" >&2
  exit 2
fi

# Путь к логам считается от расположения скрипта, а не от текущего каталога:
# иначе запуск вида bash 05/main.sh 1 из корня проекта логов не находил.
# В части 3 то же самое сделано через SCRIPT_DIR
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOG_DIR="$SCRIPT_DIR/../04"
LOG_FILES=("$LOG_DIR"/nginx_log_*.log)
if [ ! -e "${LOG_FILES[0]}" ]; then
  echo "Ошибка: не найдено ни одного файла nginx_log_*.log в $LOG_DIR" >&2
  exit 3
fi

case "$MODE" in
  1)
    # Все записи, отсортированные по коду ответа
    awk '{print $0}' "${LOG_FILES[@]}" | sort -k9,9n
    ;;
  2)
    # Все уникальные IP
    awk '{print $1}' "${LOG_FILES[@]}" | sort | uniq
    ;;
  3)
    # Все запросы с ошибками (код 4xx или 5xx)
    awk '$9 ~ /^[45][0-9][0-9]$/ {print $0}' "${LOG_FILES[@]}"
    ;;
  4)
    # Все уникальные IP среди ошибочных запросов
    awk '$9 ~ /^[45][0-9][0-9]$/ {print $1}' "${LOG_FILES[@]}" | sort | uniq
    ;;
esac 
