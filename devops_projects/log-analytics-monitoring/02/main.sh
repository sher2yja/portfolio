#!/bin/bash

# Часть 2. Заполнение файловой системы до порога свободного места.
#
# Скрипт целенаправленно занимает место на диске: создаёт папки со случайным
# расположением и останавливается, когда свободного места остаётся 1 ГБ.
# В части 7 он используется как источник нагрузки для дашбордов.
#
# По умолчанию работает внутри песочницы ./sandbox рядом со скриптом —
# всё созданное лежит в одном дереве и убирается одной командой. Разбрасывание
# по всей файловой системе, как требует задание, включается явным указанием
# корня четвёртым параметром и требует подтверждения. Подробности — в input.sh.
#
# Логика разнесена по файлам: input.sh проверяет параметры и определяет корень,
# create_structure.sh создаёт структуру, log.sh пишет журнал, output.sh
# подводит итог. main.sh только задаёт порядок.
#
# Запуск: ./main.sh az az.az 3Mb [корневой_каталог]

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
START_TIME=$(date +%s)
LOG_FILE="$SCRIPT_DIR/log.txt"

# 1. Проверка и парсинг параметров
source "$SCRIPT_DIR/input.sh" "$@"

# Журнал начинается заново при каждом запуске и первой строкой фиксирует
# корень: по нему часть 3 понимает, в каких границах убирать
: > "$LOG_FILE"
echo -e "ROOT\t$TARGET_ROOT" >> "$LOG_FILE"
echo "Область работы: $TARGET_ROOT"

# 2. Основной цикл создания структуры
source "$SCRIPT_DIR/create_structure.sh"

# 3. Вывод и логирование итоговой информации
source "$SCRIPT_DIR/output.sh" "$START_TIME" "$LOG_FILE"
