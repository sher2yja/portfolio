#!/bin/bash

# Часть 2. Проверка параметров и определение области работы.
#
# Имя и расширение вытаскиваются одним регулярным выражением через BASH_REMATCH,
# без повторного разбора строки.
#
# Значения уходят через export, а не возвращаются: скрипт подключается
# через source, и переменные нужны всем последующим шагам.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Проверка количества параметров
if [ "$#" -lt 3 ] || [ "$#" -gt 4 ]; then
  echo "Требуется 3 параметра, четвёртый необязателен."
  echo "Пример: main.sh az az.az 3Mb [корневой_каталог]"
  echo "az       - буквы для имени папки"
  echo "az.az    - буквы для имени файла и расширения"
  echo "3Mb      - размер файла"
  echo "каталог  - где размещать (по умолчанию ./sandbox рядом со скриптом)"
  exit 1
fi

FOLDER_CHARS="$1"
FILE_CHARS_EXT="$2"
FILE_SIZE="$3"
TARGET_ROOT="${4:-$SCRIPT_DIR/sandbox}"

# Проверка: только буквы, не более 7 символов для папок
if ! [[ "$FOLDER_CHARS" =~ ^[a-zA-Z]{1,7}$ ]]; then
  echo "Имя папки задается только буквами, но не более 7 символов."
  exit 1
fi

# Проверка: имя.расширение, имя <=7, расширение <=3, только буквы
if ! [[ "$FILE_CHARS_EXT" =~ ^([a-zA-Z]{1,7})\.([a-zA-Z]{1,3})$ ]]; then
  echo "Имя.расширение, только буквами, имя не больше 7 символов, расширение не больше 3 символов."
  exit 1
fi
FILE_NAME_CHARS="${BASH_REMATCH[1]}"
FILE_EXT_CHARS="${BASH_REMATCH[2]}"

# Проверка: размер файла (например, 3Mb), только Mb, не более 100
if ! [[ "$FILE_SIZE" =~ ^([1-9][0-9]?|100)[Mm][Bb]$ ]]; then
  echo "Размер файла — только Mb, от 1 до 100."
  echo "Например: 3Mb или 100mb или 20MB или 10mB"
  exit 1
fi
FILE_SIZE_MB=$(echo "$FILE_SIZE" | sed 's/[Mm][Bb]$//')

# --- Ограничение области работы -------------------------------------------
#
# Задание требует размещать папки «в различных местах файловой системы», и
# первая версия скрипта искала каталоги от корня. На рабочей машине это
# приводит к засорению: часть объектов оказывается там, куда потом трудно
# вернуться, а очистка по дате или по маске (часть 3) начинает задевать
# посторонние файлы.
#
# Поэтому область работы ограничена корнем TARGET_ROOT. По умолчанию это
# песочница рядом со скриптом: разбрасывание по каталогам сохраняется, но
# происходит внутри одного дерева, которое удаляется одной командой.
#
# Поведение из задания доступно явным указанием корня:
#   ./main.sh az az.az 3Mb /
# В этом случае скрипт требует подтверждения — случайно так не запустить.

mkdir -p "$TARGET_ROOT" 2>/dev/null
if [ ! -d "$TARGET_ROOT" ]; then
  echo "Ошибка: каталог $TARGET_ROOT не существует и не может быть создан."
  exit 1
fi
TARGET_ROOT="$(cd "$TARGET_ROOT" && pwd)"

if [ "$TARGET_ROOT" = "/" ]; then
  echo "ВНИМАНИЕ: выбран корень файловой системы."
  echo "Папки и файлы будут созданы по всей машине, пока свободного места"
  echo "не останется 1 ГБ. Убирать придётся частью 3."
  read -p "Продолжить? (введите YES заглавными): " CONFIRM
  if [ "$CONFIRM" != "YES" ]; then
    echo "Отменено."
    exit 1
  fi
fi

# Экспорт переменных для других скриптов
export FOLDER_CHARS
export FILE_NAME_CHARS
export FILE_EXT_CHARS
export FILE_SIZE_MB
export TARGET_ROOT
