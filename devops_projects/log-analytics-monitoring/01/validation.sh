#!/bin/bash

# Часть 1. Разбор и проверка шести параметров.
#
# Подключается через source, поэтому проверенные значения остаются в
# переменных вызывающего скрипта — отдельная передача не нужна.
#
# Путь обязан быть абсолютным: скрипт создаёт файлы пачками, и относительный
# путь при запуске из другого каталога привёл бы к засорению не того места.

# Получение параметров
dir=$1
folders_num=$2
folders_names=$3
files_num=$4
files_names=$5
file_size=$6

# Разбор имени файла на имя и расширение
IFS='.' read -a array_fi <<< "$files_names"

# Проверка количества параметров
if [ "$#" -ne 6 ]; then 
  echo -e "\e[91mОшибка: скрипт должен запускаться с 6 параметрами\e[0m"
  echo "Использование: $0 <путь> <количество_папок> <имя_папок> <количество_файлов> <имя_файлов> <размер>"
  exit 1
fi

# Проверка абсолютного пути
if [[ ! "$dir" =~ ^/ ]]; then
  echo -e "\e[91mОшибка: путь должен быть абсолютным: $dir\e[0m"
  exit 1
fi

# Создание рабочего каталога.
#
# sudo здесь не нужен и убран: mkdir -p и так создаёт каталог от имени
# запустившего пользователя, то есть владельцем сразу оказывается он.
# Прежняя версия вызывала следом sudo chown "$USER:$USER" — команда
# ничего не меняла, но требовала ввода пароля при каждом запуске.
#
# Если прав на запись нет, каталог не создастся, и работать дальше
# бессмысленно — лучше сказать об этом сразу.
if ! mkdir -p "$dir" 2>/dev/null; then
  echo -e "\e[91mОшибка: не удалось создать каталог $dir — нет прав\e[0m"
  exit 1
fi
dir=$(realpath "$dir")

# Проверка количества папок (натуральное число)
if [[ ! "$folders_num" =~ ^[1-9][0-9]*$ ]]; then
  echo -e "\e[91mОшибка: количество папок должно быть натуральным числом: $folders_num\e[0m"
  exit 1
fi

# Проверка имени папок (a-z, до 7 символов)
if [[ ! "$folders_names" =~ ^[a-z]{1,7}$ ]]; then
  echo -e "\e[91mОшибка: имя папок должно содержать только буквы a-z длиной 1-7 символов: $folders_names\e[0m"
  exit 1
fi

# Проверка количества файлов (натуральное число)
if [[ ! "$files_num" =~ ^[1-9][0-9]*$ ]]; then
  echo -e "\e[91mОшибка: количество файлов должно быть натуральным числом: $files_num\e[0m"
  exit 1
fi

# Проверка имени файлов (имя.расширение)
if [[ ! "$files_names" =~ ^[a-z]{1,7}\.[a-z]{1,3}$ ]]; then
  echo -e "\e[91mОшибка: имя файлов должно быть в формате 'имя.расширение': $files_names\e[0m"
  exit 1
fi

# Проверка размера файла (1-100kb)
if [[ ! "$file_size" =~ ^([1-9][0-9]?|100)kb$ ]]; then
  echo -e "\e[91mОшибка: размер файла должен быть от 1 до 100kb: $file_size\e[0m"
  exit 1
fi

# Извлечение числового значения размера
file_size_num=${file_size%kb} 