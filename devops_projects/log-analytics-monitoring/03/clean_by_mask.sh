#!/bin/bash

# Часть 3, способ 3. Удаление по маске имени.
#
# Прежняя версия обходила всю файловую систему: find / -name "$MASK".
# С маской вроде "*" под удаление попадало всё, до чего дотягивались права.
# Здесь обход ограничен корнем TARGET_ROOT, а слишком общие маски
# отклоняются: маска, состоящая только из звёздочек и вопросительных знаков,
# не задаёт ничего и означает «удалить всё подряд».
#
# Как и в способе по дате, найденное сначала показывается и удаляется
# только после подтверждения.
#
# Маска сопоставляется с ИМЕНЕМ объекта, а не с полным путём: -name, а не
# -path. Поэтому "azaza_*" сработает независимо от того, в каком подкаталоге
# лежит объект.

TARGET_ROOT="${TARGET_ROOT:?не задан корень уборки}"

read -p "Введите маску имени (например, azaza_*.az или *_020825*): " MASK

# Проверка на пустой ввод
if [ -z "$MASK" ]; then
  echo "Маска не может быть пустой"
  exit 1
fi

# Отклонение масок, не задающих ничего конкретного
if [[ "$MASK" =~ ^[*?]+$ ]]; then
  echo "Маска «$MASK» подходит под любое имя — так удалится всё содержимое."
  echo "Укажите более конкретную маску, например azaza_*.az"
  exit 1
fi

# Маска не должна содержать разделитель пути: -name работает с именем объекта
if [[ "$MASK" == */* ]]; then
  echo "Маска задаёт имя объекта, а не путь — символ «/» недопустим."
  exit 1
fi

# Сбор кандидатов внутри корня уборки
mapfile -d '' CANDIDATES < <(find "$TARGET_ROOT" -mindepth 1 -name "$MASK" -print0)

if [ ${#CANDIDATES[@]} -eq 0 ]; then
  echo "Внутри $TARGET_ROOT ничего не найдено по маске «$MASK»."
  exit 0
fi

echo "Найдено объектов: ${#CANDIDATES[@]}"
printf '  %s\n' "${CANDIDATES[@]:0:20}"
[ ${#CANDIDATES[@]} -gt 20 ] && echo "  ... и ещё $(( ${#CANDIDATES[@]} - 20 ))"

read -p "Удалить перечисленное? (y/N): " CONFIRM
if [ "$CONFIRM" != "y" ] && [ "$CONFIRM" != "Y" ]; then
  echo "Отменено."
  exit 0
fi

removed=0
for item in "${CANDIDATES[@]}"; do
  [ -e "$item" ] || continue
  rm -rf -- "$item" && removed=$((removed + 1))
done

echo "Удалено объектов верхнего уровня: $removed (вложенное удалено вместе с папками)"
