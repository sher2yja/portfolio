#!/bin/bash

# Часть 3. Удаление того, что создала часть 2.
#
# Три способа очистки, выбор — первым параметром:
#   1) по журналу — самый точный, удаляется ровно то, что записано в log.txt
#   2) по дате создания
#   3) по маске имени
#
# Пути к вспомогательным файлам строятся от SCRIPT_DIR, а не от текущего
# каталога, — скрипт работает из любого места.
# main.sh — основной управляющий скрипт для очистки

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# 1. Анализ параметров
source "$SCRIPT_DIR/input.sh" "$@"

# 2. Вызов нужного способа очистки
case "$CLEAN_MODE" in
  1) source "$SCRIPT_DIR/clean_by_log.sh" ;;
  2) source "$SCRIPT_DIR/clean_by_date.sh" ;;
  3) source "$SCRIPT_DIR/clean_by_mask.sh" ;;
  *) echo "Неизвестный режим очистки"; exit 1 ;;
esac 