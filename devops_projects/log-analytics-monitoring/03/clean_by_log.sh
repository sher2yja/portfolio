#!/bin/bash

# Часть 3, способ 1. Удаление по журналу — самый точный из трёх.
#
# Часть 2 записывает каждый созданный объект строкой вида
#   дата<TAB>тип<TAB>путь<TAB>размер
# поэтому здесь ничего угадывать не нужно: удаляется ровно то, что создано.
#
# Две вещи, из-за которых прежняя версия не работала вовсе:
#
# 1. Путь читался в переменную с именем PATH. Это системная переменная со
#    списком каталогов для поиска команд — после первой же строки журнала
#    оболочка переставала находить awk, rm и всё остальное. Здесь переменная
#    называется TARGET_PATH.
#
# 2. Команды вызывались через $WC_CMD, $AWK_CMD, $RM_CMD, которые нигде не
#    задавались. Пустая переменная означала, что вместо команды выполнялись
#    её аргументы. Вызовы заменены на обычные awk и rm.
#
# Дополнительно: перед удалением путь проверяется на принадлежность
# TARGET_ROOT. Журнал — обычный текстовый файл, его можно отредактировать
# или подменить, и без проверки строка вида "/etc" привела бы к удалению
# системного каталога.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LOG_FILE="${LOG_FILE:-$SCRIPT_DIR/../02/log.txt}"
TARGET_ROOT="${TARGET_ROOT:-$SCRIPT_DIR/../02/sandbox}"

if [ ! -f "$LOG_FILE" ]; then
  echo "Лог-файл не найден: $LOG_FILE"
  exit 1
fi

removed=0
skipped=0

# Файлы удаляются раньше папок: строки читаются в обратном порядке, а часть 2
# пишет папку перед её содержимым
while IFS=$'\t' read -r _date type TARGET_PATH _size; do
  # Служебные строки журнала: заголовок с корнем и итоговый блок
  [ "$_date" = "ROOT" ] && continue
  [ "$type" != "dir" ] && [ "$type" != "file" ] && continue
  [ -z "$TARGET_PATH" ] && continue

  # Граница: удаляем только то, что лежит внутри корня уборки
  case "$TARGET_PATH" in
    "$TARGET_ROOT"/*) ;;
    *) skipped=$((skipped + 1)); continue ;;
  esac

  if [ -e "$TARGET_PATH" ]; then
    rm -rf -- "$TARGET_PATH" && removed=$((removed + 1))
  fi
done < <(tac "$LOG_FILE")

echo "Удалено объектов: $removed"
if [ "$skipped" -gt 0 ]; then
  echo "Пропущено за пределами $TARGET_ROOT: $skipped"
fi
