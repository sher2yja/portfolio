#!/bin/bash

# Часть 3, способ 2. Удаление по времени изменения.
#
# Способ по своей природе менее точный, чем удаление по журналу: под условие
# попадает всё, что изменялось в заданном промежутке, а не только созданное
# частью 2. Поэтому здесь три ограничителя.
#
# ПЕРВОЕ И ГЛАВНОЕ. Прежняя версия выполняла
#     find / -newermt "$START" ! -newermt "$END" -delete 2>/dev/null
# то есть обходила ВСЮ файловую систему и удаляла любой файл, попавший в
# промежуток, — документы, конфигурации, чужие данные. Под sudo это сносит
# систему, а перенаправление ошибок в /dev/null скрывает происходящее.
# Здесь обход ограничен корнем TARGET_ROOT.
#
# ВТОРОЕ. Найденное сначала показывается, и только после подтверждения
# удаляется. Флаг -delete у find не используется: он срабатывает сразу,
# посмотреть список заранее с ним невозможно.
#
# ТРЕТЬЕ. Ошибки find больше не подавляются полностью — скрытые отказы
# в доступе мешают понять, что происходит.

TARGET_ROOT="${TARGET_ROOT:?не задан корень уборки}"

read -p "Введите время начала (ГГГГ-ММ-ДД ЧЧ:ММ): " START_INPUT
read -p "Введите время конца (ГГГГ-ММ-ДД ЧЧ:ММ): " END_INPUT

# Проверка на пустой ввод
if [ -z "$START_INPUT" ] || [ -z "$END_INPUT" ]; then
  echo "Время начала и конца не может быть пустым"
  exit 1
fi

# Проверка корректности формата даты
if ! date -d "$START_INPUT" >/dev/null 2>&1; then
  echo "Неверный формат даты/времени начала. Пример: 2025-07-20 12:00"
  exit 1
fi

if ! date -d "$END_INPUT" >/dev/null 2>&1; then
  echo "Неверный формат даты/времени конца. Пример: 2025-07-20 12:00"
  exit 1
fi

# Проверка логики времени
START_TS=$(date -d "$START_INPUT" +%s)
END_TS=$(date -d "$END_INPUT" +%s)

if [ "$START_TS" -gt "$END_TS" ]; then
  echo "Время начала не может быть позже времени окончания"
  exit 1
fi

# Сбор кандидатов внутри корня уборки
mapfile -d '' CANDIDATES < <(
  find "$TARGET_ROOT" -mindepth 1 \
       -newermt "$START_INPUT" ! -newermt "$END_INPUT" -print0
)

if [ ${#CANDIDATES[@]} -eq 0 ]; then
  echo "В указанном промежутке внутри $TARGET_ROOT ничего не найдено."
  exit 0
fi

echo "Найдено объектов: ${#CANDIDATES[@]}"
printf '  %s\n' "${CANDIDATES[@]:0:20}"
[ ${#CANDIDATES[@]} -gt 20 ] && echo "  ... и ещё $(( ${#CANDIDATES[@]} - 20 ))"

read -p "Удалить перечисленное? (y/N): " CONFIRM
if [ "$CONFIRM" != "y" ] && [ "$CONFIRM" != "Y" ]; then
  echo "Отменено."
  exit 0
fi

removed=0
for item in "${CANDIDATES[@]}"; do
  [ -e "$item" ] || continue
  rm -rf -- "$item" && removed=$((removed + 1))
done

echo "Удалено объектов верхнего уровня: $removed (вложенное удалено вместе с папками)"
