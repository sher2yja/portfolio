#!/bin/bash
# Минимальный вариант инициализации Swarm. Vagrantfile его не вызывает,
# работает manager.sh — он дополнительно проверяет, не поднят ли кластер уже,
# и сохраняет токен для воркеров.
#
# --advertise-addr обязателен: у машины два интерфейса (NAT от Vagrant и
# приватная сеть стенда), и без явного указания Swarm выбирает адрес сам,
# нередко NAT-овский, по которому соседние узлы до него не достучатся.

set -e
docker swarm init --advertise-addr 192.168.56.10
