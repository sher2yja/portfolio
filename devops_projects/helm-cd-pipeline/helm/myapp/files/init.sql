-- Список баз задаётся в values (postgres.databases) — файл разворачивается
-- шаблонизатором, поэтому добавить базу можно одной строкой в одном месте.
--
-- Скрипт выполняет энтрипойнт postgres ровно один раз, при инициализации
-- пустого тома, и запускает его уже подключённым к базе обслуживания.
--
-- Чего здесь намеренно нет:
--   \c postgres     — имя базы обслуживания равно POSTGRES_USER, а тот
--                     приходит из секрета. С пользователем, отличным от
--                     postgres, такой переход просто не найдёт базу.
--   OWNER postgres  — владельцем автоматически становится создающая роль.
--   DROP DATABASE   — на пустом томе удалять нечего, а на непустом скрипт
--                     не выполнится вообще: энтрипойнт пропускает initdb.
{{- range .Values.postgres.databases }}
CREATE DATABASE {{ . }};
{{- end }}
