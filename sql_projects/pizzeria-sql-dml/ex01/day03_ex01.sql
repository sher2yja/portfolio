-- Позиции меню, которые никто ни разу не заказывал.
-- Любые JOIN в этом задании запрещены, поэтому разность множеств выражается
-- подзапросом с NOT IN.
--
-- NOT IN безопасен здесь только потому, что person_order.menu_id объявлен
-- NOT NULL. Появись в подзапросе хоть один NULL — сравнение стало бы
-- неопределённым для всех строк, и запрос молча вернул бы пусто. NOT EXISTS
-- этой ловушке не подвержен и был бы устойчивее, но условие разрешает оба.
SELECT id AS menu_id
FROM menu
WHERE id NOT IN (SELECT menu_id FROM person_order)
ORDER BY menu_id;
