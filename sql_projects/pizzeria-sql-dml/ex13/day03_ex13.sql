-- Откат вчерашней акции: сначала заказы, потом сама пицца из меню.
-- Порядок обязателен. Внешний ключ person_order.menu_id объявлен без
-- ON DELETE, поэтому удаление строки меню, на которую ссылаются заказы,
-- прерывается ошибкой fk_order_menu_id — проверено запуском в обратном порядке.
--
-- Заказы удаляются по дате, а не по позиции меню: так требует условие.
-- Это безопасно ровно потому, что в исходных данных заказов на 25 февраля
-- нет — под удаление попадают только девять строк, добавленных в ex12.
DELETE
FROM person_order
WHERE order_date = '2022-02-25';

DELETE
FROM menu
WHERE pizza_name = 'greek pizza';
