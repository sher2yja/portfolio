-- Та же вставка, но без единого литерального идентификатора: и ключ,
-- и ссылка на пиццерию вычисляются подзапросами.
--
-- Форма INSERT ... SELECT вместо VALUES выбрана не ради стиля: в VALUES
-- подзапросы тоже допустимы, но SELECT позволяет собрать всю строку одним
-- выражением и переносится на вставку многих строк без переписывания.
--
-- max(id) + 1 честен ровно потому, что последовательностей в модели нет
-- и параллельных вставок не бывает. В базе с конкурентной записью такой
-- ключ — гонка: два сеанса прочитают один максимум и получат конфликт.
INSERT INTO menu (id, pizzeria_id, pizza_name, price)
SELECT (SELECT max(id) + 1 FROM menu),
       (SELECT id FROM pizzeria WHERE name = 'Dominos'),
       'sicilian pizza',
       900;
