-- Скидка 10% на greek pizza.
-- Цена считается от самой себя: UPDATE видит старое значение строки, поэтому
-- price в правой части — это цена до изменения, и повторный запуск скинет
-- ещё 10% от уже уменьшенной. Запрос не идемпотентен, и это нормально для DML;
-- важно помнить об этом при перепрогоне цепочки.
--
-- Столбец объявлен как numeric без масштаба, а множитель 0.1 имеет масштаб 1,
-- поэтому результат печатается как 720.0, а не 720: арифметика numeric
-- сохраняет масштаб самого точного операнда. Значение верное, отличается запись.
UPDATE menu
SET price = price - (price * 0.1)
WHERE pizza_name = 'greek pizza';
