-- Календарь января 2022 года, спрятанный за именем представления.
-- Генератор ряда перестаёт быть деталью запроса: в ex03 в FROM стоит
-- v_generated_dates, а не вызов функции с тремя аргументами.
--
-- CAST(... AS DATE) вместо ::date — приведение в форме ANSI SQL, разрешённой
-- условием. Оно здесь обязательно: generate_series с шагом-интервалом
-- возвращает timestamp, а требуется тип DATE.
--
-- ORDER BY внутри определения представления ничего не гарантирует внешнему
-- запросу: планировщик вправе вернуть строки в любом порядке, если сортировка
-- не запрошена снаружи. Он оставлен как часть описания, а ex03 сортирует сам.
CREATE VIEW v_generated_dates AS
SELECT CAST(gs AS DATE) AS generated_date
FROM generate_series(CAST('2022-01-01' AS DATE),
                     CAST('2022-01-31' AS DATE),
                     CAST('1 day' AS INTERVAL)) AS gs
ORDER BY generated_date;
