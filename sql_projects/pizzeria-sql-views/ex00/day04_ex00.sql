-- Два представления: женщины и мужчины отдельными «виртуальными таблицами».
-- Представление не хранит данных — это сохранённый запрос, который выполняется
-- заново при каждом обращении. Строки всегда актуальны, платой служит время
-- выполнения исходного запроса.
--
-- Столбцы перечислены явно, а не через *. Звёздочку PostgreSQL всё равно
-- разворачивает в список колонок в момент создания, так что добавленный позже
-- столбец таблицы в представление не попадёт. Явный список делает это видимым:
-- по тексту сразу понятно, что именно отдаёт представление.
CREATE VIEW v_persons_female AS
SELECT id,
       name,
       age,
       gender,
       address
FROM person
WHERE gender = 'female';

CREATE VIEW v_persons_male AS
SELECT id,
       name,
       age,
       gender,
       address
FROM person
WHERE gender = 'male';
