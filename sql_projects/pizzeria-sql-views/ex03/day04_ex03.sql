-- Дни января, в которые не было ни одного визита.
-- Пропуск в данных — это отсутствующая строка, и найти её можно только вычитая
-- журнал из полного ряда дат. Ряд даёт представление из ex02.
--
-- Условие спрашивает про людей вообще, а не про конкретного человека, поэтому
-- вычитается весь журнал целиком. EXCEPT сравнивает множества, дубликаты дат
-- в правой части значения не имеют — день либо занят, либо нет.
SELECT generated_date AS missing_date
FROM v_generated_dates
EXCEPT
SELECT visit_date
FROM person_visits
ORDER BY missing_date;
