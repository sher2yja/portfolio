-- Новый визит Дмитрия в тот же день, но в другую пиццерию — и обновление
-- снимка. Два запроса вместе показывают, ради чего существует REFRESH:
-- после вставки таблица и материализованное представление расходятся,
-- и сходятся они только по явной команде.
--
-- Прямые числа для ключа, человека и пиццерии запрещены: id вычисляется
-- как max(id) + 1, Дмитрий и DoDo Pizza ищутся по имени. Последовательностей
-- в модели нет, назначать ключ больше нечем.
--
-- DoDo Pizza выбрана не случайно. Заведение должно подходить под условие
-- представления — там есть сырная пицца за 780, дешевле 800, — быть отличным
-- от результата ex06 (Papa Johns) и не столкнуться с уникальным ключом
-- person_visits по тройке «человек — пиццерия — дата».
INSERT INTO person_visits (id, person_id, pizzeria_id, visit_date)
VALUES ((SELECT max(id) + 1 FROM person_visits),
        (SELECT id FROM person WHERE name = 'Dmitriy'),
        (SELECT id FROM pizzeria WHERE name = 'DoDo Pizza'),
        '2022-01-08');

REFRESH MATERIALIZED VIEW mv_dmitriy_visits_and_eats;
