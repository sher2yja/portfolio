-- Заказы со скидкой 10%: имя, пицца, реальная цена и цена со скидкой.
--
-- round(...) здесь не украшение. Столбец price объявлен как numeric без
-- масштаба, а множитель 0.1 имеет масштаб 1, поэтому произведение и разность
-- получают дробную часть: без округления 800 превратилось бы в 720.0.
-- Условие требует целое, и round приводит результат к нему.
--
-- Скидка считается на лету при каждом обращении — представление данных
-- не хранит. Изменится цена в меню, изменится и вывод, ничего пересчитывать
-- не нужно. Ровно этим оно отличается от материализованного из ex06.
CREATE VIEW v_price_with_discount AS
SELECT p.name,
       m.pizza_name,
       m.price,
       round(m.price - m.price * 0.1) AS discount_price
FROM person_order po
         JOIN person p ON p.id = po.person_id
         JOIN menu m ON m.id = po.menu_id
ORDER BY p.name, m.pizza_name;
