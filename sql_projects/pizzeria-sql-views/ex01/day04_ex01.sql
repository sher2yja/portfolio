-- Общий список имён из двух представлений.
-- Для запроса представление неотличимо от таблицы: его имя стоит в FROM,
-- а подставляется определение — в этом и смысл упражнения.
--
-- UNION, а не UNION ALL: условие просит один список. Наборы не пересекаются
-- по построению (gender ограничен двумя значениями), поэтому на этих данных
-- обе формы дали бы девять строк. Разница проявилась бы на тёзках разного
-- пола: в выборке остаётся только name, и UNION схлопнул бы двух разных людей
-- с одинаковым именем в одну строку.
SELECT name
FROM v_persons_female
UNION
SELECT name
FROM v_persons_male
ORDER BY name;
