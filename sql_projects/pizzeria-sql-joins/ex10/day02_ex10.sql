-- Пары людей, живущих в одном городе. Соединение таблицы с самой собой:
-- строка сравнивается со строками той же таблицы, поэтому нужны два псевдонима.
--
-- Условие p1.id > p2.id делает сразу две вещи. Отсекает пару человека с самим
-- собой (адрес у него, разумеется, совпадает) и оставляет от каждой пары одну
-- строку из двух: без него «Андрей и Анна» и «Анна и Андрей» пришли бы обе.
-- Сравнение по id, а не по имени: id уникален, а тёзки сравнялись бы и выпали.
SELECT p1.name    AS person_name1,
       p2.name    AS person_name2,
       p1.address AS common_address
FROM person p1
         INNER JOIN person p2
                    ON p1.address = p2.address
                        AND p1.id > p2.id
ORDER BY person_name1, person_name2, common_address;
