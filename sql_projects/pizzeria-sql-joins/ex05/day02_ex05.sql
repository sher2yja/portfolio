-- Женщины старше 25 лет. Единственное задание дня без соединения: все нужные
-- поля лежат в одной таблице, и добавлять сюда JOIN значило бы усложнять
-- запрос ради темы дня. Возраст сравнивается строго — «старше 25» не включает
-- ровно 25-летних.
SELECT p.name
FROM person p
WHERE p.gender = 'female'
  AND p.age > 25
ORDER BY p.name;
