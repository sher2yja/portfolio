/* Напиши запрос SELECT, который вернет имена людей (используя внутренний запрос в части SELECT), которые сделали заказы по меню с идентификаторами

13, 14 и 18, при этом дата заказа должна быть 7 января 2022 года.

Перед началом работы обязательно ознакомься с разделом «Запрещено».

Обрати внимание на пример внутреннего запроса.

SELECT 
    (SELECT ... ) AS NAME  -- это внутренний запрос в основном операторе
FROM ...
WHERE ...*/

-- Задание запрещает JOIN и IN. Отсюда обе особенности запроса:
--   имя человека достаётся скалярным подзапросом в списке SELECT,
--   а перебор меню 13/14/18 расписан через OR вместо IN (...).
--
-- Скалярный подзапрос выполняется для каждой строки внешнего запроса и обязан
-- возвращать ровно одно значение; здесь это гарантировано тем, что id таблицы
-- person — первичный ключ.
SELECT
    (SELECT name FROM person WHERE id = person_order.person_id) AS NAME
FROM person_order
WHERE person_order.order_date = '2022-01-07' and (person_order.menu_id = 13 or person_order.menu_id = 14 or person_order.menu_id = 18);