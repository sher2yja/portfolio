Anna (age:16,gender:'female',address:'Moscow')

В конце добавь сортировку по этому вычисляемому полю в порядке возрастания. Обрати особое внимание на правильное использование кавычек в формуле!*/

-- Пробел перед '(age:' обязателен: в образце вывода он есть — «Anna (age:16,...».
-- В сданной версии его не было, строка склеивалась как «Anna(age:16,...».
--
-- Одинарная кавычка внутри строкового литерала удваивается: ''' — это
-- закрывающая кавычка литерала, экранированная кавычка и открывающая.
SELECT (name || ' (age:' || age || ',gender:''' || gender || ''',address:''' || address || ''')') AS person_information
