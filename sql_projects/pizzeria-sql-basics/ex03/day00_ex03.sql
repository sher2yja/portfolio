-- Задание 03: Погружение в мир SQL
-- Составь запрос SELECT, который вернет уникальные идентификаторы людей (без дубликатов), посетивших пиццерии в период с 6 по 9 января 2022 года (включительно), либо посетивших пиццерии с идентификатором 2.
-- Результат отсортируй по идентификатору человека в порядке убывания.

-- Скобки вокруг BETWEEN обязательны по смыслу: AND связывает сильнее OR,
-- и без них условие прочиталось бы как «дата >= 6 января AND (дата <= 9 января
-- OR pizzeria_id = 2)» — то есть посещения пиццерии 2 до 6 января потерялись бы.
--
-- DISTINCT убирает повторы: один человек мог прийти в эти дни несколько раз.
SELECT DISTINCT person_id
FROM person_visits
WHERE (visit_date BETWEEN '2022-01-06' AND '2022-01-09') OR pizzeria_id = 2
ORDER BY person_id DESC; -- DESC – направление сортировки: Descending (убывающий порядок)